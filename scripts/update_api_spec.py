"""Refresh docs/api/solution-api.md from the official gridX Solution API spec.

gridX publishes its OpenAPI document in the developer forum thread
https://community.developer.gridx.de/t/gridx-api-documentation/213, where a bot
replaces the attached gridx-public.json whenever the API changes. The file is
close to 8 MB, so the repository keeps a digest instead: every path with its
operations, summaries and the field names of request and response bodies. A
new field or endpoint then shows up as a readable diff.

Usage:
    python scripts/update_api_spec.py            # rewrite the digest
    python scripts/update_api_spec.py --check    # CI mode: exit 1 on drift
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import urllib.request
from pathlib import Path

THREAD_URL = "https://community.developer.gridx.de/t/gridx-api-documentation/213.json"
FORUM_BASE = "https://community.developer.gridx.de"
DIGEST = Path(__file__).resolve().parent.parent / "docs" / "api" / "solution-api.md"
METHODS = ("get", "post", "put", "patch", "delete")
MAX_DEPTH = 2


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "ha-gridx spec check"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return resp.read()


def find_spec_url() -> str:
    thread = json.loads(fetch(THREAD_URL))
    first_post = thread["post_stream"]["posts"][0]["cooked"]
    match = re.search(r'href="(/uploads/[^"]+\.json)"', first_post)
    if not match:
        raise SystemExit("no .json attachment found in the forum thread")
    return FORUM_BASE + match.group(1)


class Digest:
    def __init__(self, spec: dict) -> None:
        self.spec = spec
        self.schemas = spec.get("components", {}).get("schemas", {})

    def resolve(self, schema: dict) -> dict:
        seen = 0
        while "$ref" in schema and seen < 10:
            schema = self.schemas.get(schema["$ref"].split("/")[-1], {})
            seen += 1
        if "allOf" in schema:
            merged: dict = {"type": "object", "properties": {}}
            for part in schema["allOf"]:
                part = self.resolve(part)
                merged["properties"].update(part.get("properties", {}))
                if part.get("type") not in (None, "object"):
                    merged["type"] = part["type"]
                if "items" in part:
                    merged["items"] = part["items"]
            return merged
        return schema

    def fields(self, schema: dict, depth: int = 0, prefix: str = "") -> list[str]:
        schema = self.resolve(schema)
        if schema.get("type") == "array":
            return self.fields(schema.get("items", {}), depth, prefix + "[]")
        out: list[str] = []
        for name, sub in sorted((schema.get("properties") or {}).items()):
            sub = self.resolve(sub)
            kind = sub.get("type", "object")
            if kind == "array":
                item = self.resolve(sub.get("items", {}))
                kind = f"array of {item.get('type', 'object')}"
                if depth < MAX_DEPTH and item.get("properties"):
                    out.append(f"{prefix}{name} ({kind})")
                    out += self.fields(item, depth + 1, f"{prefix}{name}[].")
                    continue
            if kind == "object" and depth < MAX_DEPTH and sub.get("properties"):
                out.append(f"{prefix}{name} (object)")
                out += self.fields(sub, depth + 1, f"{prefix}{name}.")
                continue
            enum = sub.get("enum")
            suffix = f" {enum}" if enum and len(enum) <= 8 else ""
            out.append(f"{prefix}{name} ({kind}){suffix}")
        return out

    def body(self, content: dict) -> list[str]:
        if not content:
            return []
        media = next(iter(content.values()))
        return self.fields(media.get("schema", {}))

    def render(self, source_url: str, sha256: str) -> str:
        lines = [
            "# gridX Solution API digest",
            "",
            "Generated by `scripts/update_api_spec.py` from the OpenAPI document gridX",
            "publishes in its developer forum. Do not edit by hand.",
            "",
            f"- Title: {self.spec['info'].get('title')} {self.spec['info'].get('version')}",
            f"- Source: {source_url}",
            f"- SHA-256 of the document: {sha256}",
            f"- Paths: {len(self.spec['paths'])}",
            "",
        ]
        for path in sorted(self.spec["paths"]):
            ops = self.spec["paths"][path]
            lines.append(f"## {path}")
            lines.append("")
            for method in METHODS:
                if method not in ops:
                    continue
                op = ops[method]
                summary = (op.get("summary") or "").strip()
                lines.append(f"### {method.upper()} {summary}".rstrip())
                params = [
                    p["name"] + ("*" if p.get("required") else "")
                    for p in op.get("parameters", [])
                    if isinstance(p, dict) and "name" in p
                ]
                if params:
                    lines.append(f"- Parameters: {', '.join(params)}")
                req = self.body(op.get("requestBody", {}).get("content", {}))
                if req:
                    lines.append("- Request:")
                    lines += [f"  - {f}" for f in req]
                for status, resp in sorted(op.get("responses", {}).items()):
                    if not status.startswith("2"):
                        continue
                    fields = self.body(resp.get("content", {}))
                    if fields:
                        lines.append(f"- Response {status}:")
                        lines += [f"  - {f}" for f in fields]
                lines.append("")
        return "\n".join(lines).rstrip() + "\n"


def _without_source_line(text: str) -> str:
    # the upload URL changes with every new attachment, so it is not drift
    return "\n".join(
        line for line in text.splitlines() if not line.startswith("- Source:")
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="exit 1 when the digest is out of date"
    )
    parser.add_argument(
        "--spec",
        type=Path,
        help="use a local copy of the document instead of downloading",
    )
    args = parser.parse_args()

    if args.spec:
        raw = args.spec.read_bytes()
        source_url = str(args.spec)
    else:
        source_url = find_spec_url()
        raw = fetch(source_url)
    spec = json.loads(raw)
    sha256 = hashlib.sha256(raw).hexdigest()
    digest = Digest(spec).render(source_url, sha256)

    current = DIGEST.read_text() if DIGEST.exists() else ""
    if _without_source_line(current) == _without_source_line(digest):
        print("OK: docs/api/solution-api.md matches the published spec.")
        return 0
    if args.check:
        print(
            "DRIFT: the published gridX Solution API differs from docs/api/solution-api.md."
        )
        print("Run scripts/update_api_spec.py and review the diff.")
        return 1
    DIGEST.parent.mkdir(parents=True, exist_ok=True)
    DIGEST.write_text(digest)
    print(f"Updated {DIGEST} ({len(spec['paths'])} paths, sha256 {sha256[:12]}).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
